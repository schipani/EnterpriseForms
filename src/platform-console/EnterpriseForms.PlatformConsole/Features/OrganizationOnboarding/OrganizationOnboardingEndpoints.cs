using AuthorizationAuthority.Contracts.V1;
using EnterpriseForms.PlatformConsole.Composition;
using EnterpriseForms.PlatformConsole.Features.OperatorApprovals;
using EnterpriseForms.PlatformConsole.Features.Session;
using EnterpriseForms.PlatformConsole.Infrastructure;
using Microsoft.AspNetCore.Http.HttpResults;

namespace EnterpriseForms.PlatformConsole.Features.OrganizationOnboarding;

/// <summary>One initial owner as the browser may send it (unknown members are refused).</summary>
public sealed record OnboardingOwnerInput(string IssuerUri, string SubjectIdentifier, string DisplayNameHint, string VerificationMethod, string VerificationReference);

/// <summary>A new onboarding request as the browser may send it. The organization id and every owner's user id are generated by the Authority.</summary>
public sealed record OnboardingCreateInput(string IdempotencyKey, string OrganizationDisplayName, IReadOnlyList<OnboardingOwnerInput> InitialOwners, string Justification, bool DryRun = false);

/// <summary>
/// C8 onboarding (C-104): PG-072 Organizations, PG-073 New organization and PG-074 Onboarding request (feature owner: Platform
/// administration / Security). Every endpoint needs a live console session (and CSRF on POST); the operator is always the session's.
/// Reads and decisions are the Authority's platform-plane operations; this layer adds no rule. Decisions go through the same
/// dry-run → fingerprint check → Vault signing → submit flow as membership approvals. Organization metadata and owner identities only:
/// no record, document, team or share data, and no key operation (key custody is a separate development step, never a browser action).
/// </summary>
public static class OrganizationOnboardingEndpoints
{
    public static IEndpointRouteBuilder MapOrganizationOnboardingEndpoints(this IEndpointRouteBuilder endpoints)
    {
        var group = endpoints.MapGroup(ConsoleSessionCookie.ApiPath + "/v1").WithTags("OrganizationOnboarding").AddEndpointFilter<RequireOperatorSession>();

        group.MapGet("/organizations", static async Task<Ok<OrganizationDirectoryPage>> (string? q, string? filter, string? cursor, int? limit, HttpContext http, AuthorityPlatformClient authority, OperatorSessionStore store, IHostEnvironment environment, CancellationToken cancellationToken) =>
            {
                var session = RequireOperatorSession.Current(http);
                return TypedResults.Ok(await OperatorSessionGuard.RunAsync(http, session, store, environment, () =>
                    authority.SearchOrganizationsAsync(session.SubjectIdentifier, new OrganizationDirectorySearchRequest(q, filter, cursor, limit), SessionEndpoints.Correlation(http), cancellationToken)).ConfigureAwait(false));
            })
            .WithName("SearchOrganizations")
            .WithSummary("PG-072: organizations with lifecycle and owner, Security Administrator and member counts (15 per page by default, at most 50).");

        group.MapGet("/organizations/{organizationId:guid}", static async Task<Ok<OrganizationDirectoryDetail>> (Guid organizationId, HttpContext http, AuthorityPlatformClient authority, OperatorSessionStore store, IHostEnvironment environment, CancellationToken cancellationToken) =>
            {
                var session = RequireOperatorSession.Current(http);
                return TypedResults.Ok(await OperatorSessionGuard.RunAsync(http, session, store, environment, () =>
                    authority.GetOrganizationAsync(session.SubjectIdentifier, organizationId, SessionEndpoints.Correlation(http), cancellationToken)).ConfigureAwait(false));
            })
            .WithName("GetOrganization")
            .WithSummary("PG-072 details: owner identities, counts and onboarding provenance. The Authority audits each view (fail closed).");

        group.MapGet("/organization-onboarding", static async Task<Ok<OrganizationOnboardingPage>> (string? q, string? status, string? cursor, int? limit, HttpContext http, AuthorityPlatformClient authority, OperatorSessionStore store, IHostEnvironment environment, CancellationToken cancellationToken) =>
            {
                var session = RequireOperatorSession.Current(http);
                return TypedResults.Ok(await OperatorSessionGuard.RunAsync(http, session, store, environment, () =>
                    authority.SearchOnboardingAsync(session.SubjectIdentifier, new OrganizationOnboardingSearchRequest(q, status, cursor, limit), SessionEndpoints.Correlation(http), cancellationToken)).ConfigureAwait(false));
            })
            .WithName("SearchOrganizationOnboarding")
            .WithSummary("PG-074 queue: onboarding requests, newest first (15 per page by default), and the owner issuers this environment accepts.");

        group.MapPost("/organization-onboarding", static async Task<Ok<OrganizationOnboardingCreateResponse>> (OnboardingCreateInput input, HttpContext http, AuthorityPlatformClient authority, OperatorSessionStore store, IHostEnvironment environment, CancellationToken cancellationToken) =>
            {
                var session = RequireOperatorSession.Current(http);
                var request = new OrganizationOnboardingCreateRequest(input.IdempotencyKey, input.OrganizationDisplayName,
                    (input.InitialOwners ?? []).Select(o => new OrganizationOnboardingOwnerInput(o.IssuerUri, o.SubjectIdentifier, o.DisplayNameHint, o.VerificationMethod, o.VerificationReference)).ToList(),
                    input.Justification, input.DryRun);
                return TypedResults.Ok(await OperatorSessionGuard.RunAsync(http, session, store, environment, () =>
                    authority.CreateOnboardingAsync(session.SubjectIdentifier, request, SessionEndpoints.Correlation(http), cancellationToken)).ConfigureAwait(false));
            })
            .RequireRateLimiting(ConsoleRateLimits.DecisionPolicy)
            .WithName("CreateOrganizationOnboarding")
            .WithSummary("PG-073: create an immutable onboarding request (dryRun validates only). Creating grants nothing; approvals carry each operator's own evidence.");

        group.MapGet("/organization-onboarding/{requestId:guid}", static async Task<Ok<OrganizationOnboardingDetail>> (Guid requestId, HttpContext http, AuthorityPlatformClient authority, OperatorSessionStore store, IHostEnvironment environment, CancellationToken cancellationToken) =>
            {
                var session = RequireOperatorSession.Current(http);
                return TypedResults.Ok(await OperatorSessionGuard.RunAsync(http, session, store, environment, () =>
                    authority.GetOnboardingAsync(session.SubjectIdentifier, requestId, SessionEndpoints.Correlation(http), cancellationToken)).ConfigureAwait(false));
            })
            .WithName("GetOrganizationOnboarding")
            .WithSummary("PG-074: the request, its frozen statement and fingerprint, owners, approvals, key custody status, activation and the operator's eligibility.");

        MapDecision(group, "/organization-onboarding/{requestId:guid}/approvals", OperatorDecisions.Approve, "ApproveOrganizationOnboarding",
            "The signed-in operator's approval. The second valid approval by a different operator approves the request (key custody follows).");
        MapDecision(group, "/organization-onboarding/{requestId:guid}/approvals/withdraw", OperatorDecisions.Withdraw, "WithdrawOrganizationOnboardingApproval", "Withdraws the signed-in operator's own approval.");
        MapDecision(group, "/organization-onboarding/{requestId:guid}/reject", OperatorDecisions.Reject, "RejectOrganizationOnboarding", "Rejects a request awaiting approval; nothing is created.");
        MapDecision(group, "/organization-onboarding/{requestId:guid}/cancel", OperatorDecisions.Cancel, "CancelOrganizationOnboarding", "Cancels an approved request before initialization; nothing is created.");
        MapDecision(group, "/organization-onboarding/{requestId:guid}/initialize", OperatorDecisions.Initialize, "InitializeOrganization",
            "Creates the organization, its initial owners and owner roles in one Authority transaction after verifying the custody key; usable once the first change is projected and anchored.");
        return endpoints;
    }

    private static void MapDecision(RouteGroupBuilder group, string pattern, string decision, string name, string summary)
    {
        group.MapPost(pattern, async Task<Ok<OrganizationOnboardingDecisionResponse>> (Guid requestId, OperatorDecisionInput input, HttpContext http, OperatorDecisionService decisions, CancellationToken cancellationToken) =>
                TypedResults.Ok(await decisions.DecideOnboardingAsync(http, RequireOperatorSession.Current(http), requestId, decision, input, cancellationToken).ConfigureAwait(false)))
            .RequireRateLimiting(ConsoleRateLimits.DecisionPolicy)
            .WithName(name)
            .WithSummary(summary);
    }
}
