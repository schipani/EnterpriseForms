using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace EnterpriseForms.Experiments.ManagedHsmProbe;

/// <summary>
/// Published TEST-ONLY HMAC keys. They exist to make the vectors reproducible and to be imported into a throwaway,
/// non-production Managed HSM. No EnterpriseForms deployment key equals or derives from either of them.
/// </summary>
internal static class TestKeys
{
    /// <summary>The published RowHmac/v1 test key (trust_authority/row-integrity-v1.test-vectors.json testHmacKeyHex).</summary>
    public const string TestKey1Id = "e6a-test-key-1";

    /// <summary>A second published test key, used only as a distinct second key version in the version experiment.</summary>
    public const string TestKey2Id = "e6a-test-key-2";

    public static readonly IReadOnlyDictionary<string, string> KeyHexById = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        [TestKey1Id] = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f",
        [TestKey2Id] = "202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f",
    };

    public static byte[] Get(string testKeyId) =>
        KeyHexById.TryGetValue(testKeyId, out var hex) ? Codec.FromHex(hex) : throw new ArgumentException($"unknown test key id '{testKeyId}'", nameof(testKeyId));
}

internal sealed class ReferenceVectorSet
{
    public const string SchemaName = "EnterpriseForms/E6a/ManagedHsmHmacProbe/reference-vectors/v1";

    public const string LengthInputRule = "input[i] = (byte)(i mod 256) for i = 0 .. inputLength-1";

    public static readonly int[] RequiredLengths = [0, 1, 31, 32, 33, 64, 256, 1024, 4096, 65536];

    public string Schema { get; set; } = SchemaName;

    public string Purpose { get; set; } = string.Empty;

    public string Warning { get; set; } = string.Empty;

    public string LengthInput { get; set; } = LengthInputRule;

    public string RowVectorSource { get; set; } = string.Empty;

    public List<ReferenceTestKey> TestKeys { get; set; } = [];

    public List<ReferenceVector> Vectors { get; set; } = [];
}

internal sealed class ReferenceTestKey
{
    public string TestKeyId { get; set; } = string.Empty;

    public string KeyHex { get; set; } = string.Empty;

    public string KeySource { get; set; } = string.Empty;
}

internal sealed class ReferenceVector
{
    public string VectorId { get; set; } = string.Empty;

    /// <summary><c>Length</c> (generated by <see cref="ReferenceVectorSet.LengthInputRule"/>) or <c>RowHmacV1</c> (a published synthetic canonical payload).</summary>
    public string VectorKind { get; set; } = string.Empty;

    public int InputLength { get; set; }

    /// <summary>Present for RowHmacV1 vectors only; Length vector inputs are regenerated from the rule.</summary>
    public string? InputHex { get; set; }

    public string InputSha256Hex { get; set; } = string.Empty;

    /// <summary>For RowHmacV1 vectors: the published rowSignatureHexWithTestKey (must equal the raw-message MAC under e6a-test-key-1).</summary>
    public string? PublishedRowSignatureHex { get; set; }

    public List<ReferenceMac> Macs { get; set; } = [];

    public byte[] Input() => VectorKind == "Length" ? ReferenceVectorGenerator.LengthInput(InputLength) : Codec.FromHex(InputHex ?? string.Empty);

    public ReferenceMac MacFor(string testKeyId) => Macs.Single(m => m.TestKeyId == testKeyId);
}

internal sealed class ReferenceMac
{
    public string TestKeyId { get; set; } = string.Empty;

    /// <summary>HMAC-SHA-256(key, input): the existing EnterpriseForms construction (LocalHmacProvider, VaultTransitHmacProvider).</summary>
    public string RawMessageHmacSha256Hex { get; set; } = string.Empty;

    /// <summary>HMAC-SHA-256(key, SHA-256(input)): what the documented Managed HSM "sign hash" path produces for a locally hashed input.</summary>
    public string DigestMessageHmacSha256Hex { get; set; } = string.Empty;

    public bool RawEqualsDigest { get; set; }
}

internal static class ReferenceVectorGenerator
{
    public static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
    };

    public static byte[] LengthInput(int length)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(length);
        var bytes = new byte[length];
        for (var i = 0; i < length; i++)
        {
            bytes[i] = unchecked((byte)i);
        }

        return bytes;
    }

    /// <summary>Builds the vector set from the length rule and the published RowHmac/v1 vectors (synthetic data only).</summary>
    public static ReferenceVectorSet Generate(string rowVectorJson, string rowVectorSourceName)
    {
        var set = new ReferenceVectorSet
        {
            Purpose = "E-6a: decide whether Azure Managed HSM HS256 reproduces EnterpriseForms HMAC-SHA-256 over raw canonical bytes (Experiment B) or only over a SHA-256 digest (Experiment A).",
            Warning = "TEST KEYS ONLY. Both keys are published. They may be imported only into a throwaway non-production Managed HSM. No EnterpriseForms deployment key equals or derives from them.",
            RowVectorSource = rowVectorSourceName,
            TestKeys = [.. TestKeys.KeyHexById.Select(k => new ReferenceTestKey
            {
                TestKeyId = k.Key,
                KeyHex = k.Value,
                KeySource = k.Key == TestKeys.TestKey1Id ? "trust_authority/row-integrity-v1.test-vectors.json testHmacKeyHex (published RowHmac/v1 test key)" : "E-6a published second test key (bytes 0x20..0x3f)",
            })],
        };

        foreach (var length in ReferenceVectorSet.RequiredLengths)
        {
            set.Vectors.Add(Build($"len-{length.ToString("D5", System.Globalization.CultureInfo.InvariantCulture)}", "Length", LengthInput(length), null, null));
        }

        using var document = JsonDocument.Parse(rowVectorJson);
        var root = document.RootElement;
        if (root.GetProperty("testHmacKeyHex").GetString() != TestKeys.KeyHexById[TestKeys.TestKey1Id])
        {
            throw new InvalidOperationException("the RowHmac/v1 vector file uses a different test key than e6a-test-key-1");
        }

        foreach (var testCase in root.GetProperty("cases").EnumerateArray())
        {
            var expected = testCase.GetProperty("expected");
            var hex = expected.GetProperty("canonicalBytesHex").GetString() ?? throw new InvalidOperationException("case without canonicalBytesHex");
            var published = expected.GetProperty("rowSignatureHexWithTestKey").GetString();
            set.Vectors.Add(Build("row-" + testCase.GetProperty("caseId").GetString(), "RowHmacV1", Codec.FromHex(hex), hex.ToLowerInvariant(), published));
        }

        return set;
    }

    public static string Serialize(ReferenceVectorSet set) => JsonSerializer.Serialize(set, JsonOptions).ReplaceLineEndings("\n") + "\n";

    public static ReferenceVectorSet Deserialize(string json) =>
        JsonSerializer.Deserialize<ReferenceVectorSet>(json, JsonOptions) ?? throw new InvalidOperationException("empty reference vector file");

    /// <summary>The committed vector file, embedded in the probe so a run cannot silently use edited expectations.</summary>
    public static ReferenceVectorSet LoadEmbedded()
    {
        using var stream = typeof(ReferenceVectorGenerator).Assembly.GetManifestResourceStream("e6a-reference-vectors.json")
                           ?? throw new InvalidOperationException("embedded reference vectors missing");
        using var reader = new StreamReader(stream);
        return Deserialize(reader.ReadToEnd());
    }

    private static ReferenceVector Build(string id, string kind, byte[] input, string? inputHex, string? published)
    {
        var digest = SHA256.HashData(input);
        var vector = new ReferenceVector
        {
            VectorId = id,
            VectorKind = kind,
            InputLength = input.Length,
            InputHex = inputHex,
            InputSha256Hex = Codec.ToHex(digest),
            PublishedRowSignatureHex = published,
        };
        foreach (var (keyId, _) in TestKeys.KeyHexById)
        {
            var key = TestKeys.Get(keyId);
            // Two separately computed expectations: the MAC over the raw message and the MAC over its SHA-256 digest.
            var raw = HMACSHA256.HashData(key, input);
            var overDigest = HMACSHA256.HashData(key, digest);
            vector.Macs.Add(new ReferenceMac
            {
                TestKeyId = keyId,
                RawMessageHmacSha256Hex = Codec.ToHex(raw),
                DigestMessageHmacSha256Hex = Codec.ToHex(overDigest),
                RawEqualsDigest = raw.AsSpan().SequenceEqual(overDigest),
            });
        }

        return vector;
    }
}

/// <summary>
/// An independent RFC 2104 HMAC-SHA-256 built only from SHA-256, used to cross-check <see cref="HMACSHA256"/> in the local
/// self-checks (it is never used to produce evidence that leaves the process).
/// </summary>
internal static class Rfc2104HmacSha256
{
    private const int BlockSize = 64;

    public static byte[] Compute(ReadOnlySpan<byte> key, ReadOnlySpan<byte> message)
    {
        var block = new byte[BlockSize];
        if (key.Length > BlockSize)
        {
            SHA256.HashData(key).CopyTo(block, 0);
        }
        else
        {
            key.CopyTo(block);
        }

        var inner = new byte[BlockSize + message.Length];
        var outer = new byte[BlockSize + 32];
        for (var i = 0; i < BlockSize; i++)
        {
            inner[i] = (byte)(block[i] ^ 0x36);
            outer[i] = (byte)(block[i] ^ 0x5c);
        }

        message.CopyTo(inner.AsSpan(BlockSize));
        SHA256.HashData(inner).CopyTo(outer, BlockSize);
        return SHA256.HashData(outer);
    }
}
