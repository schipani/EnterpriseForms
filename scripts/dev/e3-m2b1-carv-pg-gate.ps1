<#
.SYNOPSIS
  E3-M2b-1 CARV real-PostgreSQL gate (M2-CARV-PG; OD-M2-12, OD-M2-29). Development/Testing only.

.DESCRIPTION
  Re-runnable gate for the content acceptance rule version (CARV) fence (docs/security/E3_M2B_IMPLEMENTATION_CONTRACT.md §19/§20).
  For every legacy (pre-CARV) Authority build it runs, each on a fresh disposable postgres:18.0 container (tmpfs data, loopback
  port, removed afterwards; no other stack, volume or database is touched):

    Harness A  the design-gate scenarios against the legacy build, with the REAL migration of this tree applied by this tree's
               own `--migrate` and its EF-scripted Down; CARV instances are a test-only database emulation.
    Harness B  the REAL CARV build of this tree in-process (its ContentService rules, store refusal mapping, readiness guard),
               with the legacy build driven through the legacy agent child process. No emulation trigger.
    Harness F  E3-M2b-1F: the REAL floor migration, applied only by this tree's explicit --apply-content-acceptance-floor
               command (never by --migrate), with the real CARV build and the legacy agent (including a lagging clock).

  Legacy builds come from -LegacyBinariesRoot\<first 7 characters of the commit>\ when present (for example the frozen
  design-gate builds whose hashes are in docs/evidence/e3-m2b1-carv), otherwise from `git archive` of the commit, built in the
  work directory. The harness sources live in tools/experiments/e3-m2b1-carv-gate and are built as copies in the work
  directory. Exit code 0 only if every check of every run passed. Not Stage B, not a security-test stack run, no Azure call.

.EXAMPLE
  powershell -File scripts\dev\e3-m2b1-carv-pg-gate.ps1 -LegacyBinariesRoot C:\frozen\carv -Evidence C:\out\carv
#>
param(
    [string[]]$LegacyCommits = @('66f0aa7b257d984555533ceb10dfccfa921aa273', 'de1729be569aa564d8a43a6c422f88a731ca48d1'),
    [string]$LegacyBinariesRoot,
    [string]$WorkDir,
    [string]$Evidence,
    [int]$Port = 55440
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$gate = Join-Path $repo 'tools\experiments\e3-m2b1-carv-gate'
$previousMigration = '20261112003342_AuthoritySearchAccessIx5Verification'
$carvMigration = '20261115014221_AuthorityContentAcceptanceRuleVersion'
if (-not $WorkDir) { $WorkDir = Join-Path ([System.IO.Path]::GetTempPath()) ('e3-m2b1-carv-gate-' + [guid]::NewGuid().ToString('N').Substring(0, 8)) }
if (-not $Evidence) { $Evidence = Join-Path $WorkDir 'evidence' }
New-Item -ItemType Directory -Force $WorkDir, $Evidence, (Join-Path $WorkDir 'sql') | Out-Null
Write-Output "work directory: $WorkDir"

function Invoke-Checked([string]$exe, [string[]]$arguments) {
    # Out-Host: native output must not become part of a function's return value.
    & $exe @arguments | Out-Host
    if ($LASTEXITCODE -ne 0) { throw "$exe $($arguments -join ' ') failed with exit code $LASTEXITCODE" }
}

function Save-Hashes([string]$directory, [string]$path) {
    Get-ChildItem $directory -Filter '*.dll' | Where-Object { $_.Name -like 'AuthorizationAuthority.*' -or $_.Name -eq 'EnterpriseForms.Integrity.dll' } | Sort-Object Name |
        Get-FileHash -Algorithm SHA256 | ForEach-Object { "$($_.Hash.ToLowerInvariant()) *$(Split-Path -Leaf $_.Path)" } | Set-Content -Encoding ascii $path
}

function Build-Copy([string]$source, [string]$target, [string]$binaries) {
    if (Test-Path $target) { Remove-Item -Recurse -Force $target }
    New-Item -ItemType Directory -Force $target | Out-Null
    Copy-Item (Join-Path $source '*') $target -Recurse
    Invoke-Checked 'dotnet' @('build', (Get-ChildItem $target -Filter '*.csproj').FullName, '-c', 'Release', '-nologo', '-v', 'q', "-p:CarvBinaries=$binaries")
    Join-Path $target 'bin\Release\net10.0'
}

if (-not (docker image inspect postgres:18.0 --format '{{.Id}}' 2>$null)) { throw 'postgres:18.0 is not present locally (docker pull postgres:18.0 first)' }

# 1. The build under test (this working tree) and the real migration scripts generated by EF from it.
Invoke-Checked 'dotnet' @('build', (Join-Path $repo 'src\authority\AuthorizationAuthority.Api\AuthorizationAuthority.Api.csproj'), '-c', 'Release', '-nologo', '-v', 'q')
$new = Join-Path $WorkDir 'new'
Copy-Item (Join-Path $repo 'src\authority\AuthorizationAuthority.Api\bin\Release\net10.0') $new -Recurse -Force
Save-Hashes $new (Join-Path $Evidence 'new-sha256.txt')
Push-Location (Join-Path $repo 'src\authority\AuthorizationAuthority.Infrastructure')
try {
    # Two contexts live in the Infrastructure assembly since E3-M2b-1F (the floor has its own): name the Authority context.
    Invoke-Checked 'dotnet' @('ef', 'migrations', 'script', $previousMigration, $carvMigration, '--context', 'AuthorityDbContext', '-o', (Join-Path $WorkDir 'sql\real_up.sql'))
    Invoke-Checked 'dotnet' @('ef', 'migrations', 'script', $carvMigration, $previousMigration, '--context', 'AuthorityDbContext', '-o', (Join-Path $WorkDir 'sql\real_down.sql'))
}
finally { Pop-Location }
foreach ($file in Get-ChildItem (Join-Path $gate 'sql') -Filter '*.sql.txt') { Copy-Item $file.FullName (Join-Path $WorkDir ('sql\' + $file.Name -replace '\.txt$', '')) }
Get-ChildItem (Join-Path $WorkDir 'sql') -Filter '*.sql' | Get-FileHash -Algorithm SHA256 | ForEach-Object { "$($_.Hash.ToLowerInvariant()) $(Split-Path -Leaf $_.Path)" } | Set-Content -Encoding ascii (Join-Path $Evidence 'sql-sha256.txt')

# 2. Legacy builds.
$legacy = @{}
foreach ($commit in $LegacyCommits) {
    $short = $commit.Substring(0, 7)
    $target = Join-Path $WorkDir "legacy-$short"
    if ($LegacyBinariesRoot -and (Test-Path (Join-Path $LegacyBinariesRoot "$short\AuthorizationAuthority.Api.dll"))) {
        Copy-Item (Join-Path $LegacyBinariesRoot $short) $target -Recurse -Force
        "prebuilt: <LegacyBinariesRoot>\$short (local path not recorded)" | Set-Content -Encoding ascii (Join-Path $Evidence "legacy-$short-origin.txt")
    }
    else {
        $archive = Join-Path $WorkDir "src-$short.zip"
        $source = Join-Path $WorkDir "src-$short"
        Invoke-Checked 'git' @('-C', $repo, 'archive', '--format=zip', '-o', $archive, $commit)
        Expand-Archive -Path $archive -DestinationPath $source -Force
        Invoke-Checked 'dotnet' @('build', (Join-Path $source 'src\authority\AuthorizationAuthority.Api\AuthorizationAuthority.Api.csproj'), '-c', 'Release', '-nologo', '-v', 'q')
        Copy-Item (Join-Path $source 'src\authority\AuthorizationAuthority.Api\bin\Release\net10.0') $target -Recurse -Force
        "git archive $commit, Release build in the work directory" | Set-Content -Encoding ascii (Join-Path $Evidence "legacy-$short-origin.txt")
    }

    Save-Hashes $target (Join-Path $Evidence "legacy-$short-sha256.txt")
    $legacy[$short] = $target
}

# 3. Harness builds (copies outside the repository).
$harnessB = Build-Copy (Join-Path $gate 'HarnessB') (Join-Path $WorkDir 'harnessB') $new
$harnessF = Build-Copy (Join-Path $gate 'HarnessF') (Join-Path $WorkDir 'harnessF') $new
$harnessA = @{}; $agents = @{}
foreach ($short in $legacy.Keys) {
    $harnessA[$short] = Build-Copy (Join-Path $gate 'HarnessA') (Join-Path $WorkDir "harnessA-$short") $legacy[$short]
    $agents[$short] = Build-Copy (Join-Path $gate 'LegacyAgent') (Join-Path $WorkDir "agent-$short") $legacy[$short]
}

# 4. Runs, each on its own disposable PostgreSQL container.
function Invoke-GateRun([string]$kind, [string]$short) {
    $name = "carv-gate-$($kind.ToLowerInvariant())-$short-" + [guid]::NewGuid().ToString('N').Substring(0, 6)
    $runEvidence = Join-Path $Evidence "harness-$($kind.ToLowerInvariant())-$short"
    New-Item -ItemType Directory -Force $runEvidence | Out-Null
    $adminPassword = 'carv-admin-' + [guid]::NewGuid().ToString('N')
    $runtimePassword = 'carv-runtime-' + [guid]::NewGuid().ToString('N')
    $code = 99
    try {
        docker run -d --rm --name $name -e "POSTGRES_PASSWORD=$adminPassword" -e POSTGRES_DB=carv -p "127.0.0.1:${Port}:5432" --tmpfs /var/lib/postgresql:rw postgres:18.0 | Out-Null
        for ($i = 0; $i -lt 60; $i++) {
            docker exec $name pg_isready -U postgres -d carv 2>$null | Out-Null
            if ($LASTEXITCODE -eq 0) { break }
            Start-Sleep -Milliseconds 500
        }
        Start-Sleep -Seconds 2
        docker exec $name psql -U postgres -d carv -v ON_ERROR_STOP=1 -qAt -c "CREATE ROLE authority_runtime LOGIN PASSWORD '$runtimePassword' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS" | Out-Null
        $admin = "Host=127.0.0.1;Port=$Port;Database=carv;Username=postgres;Password=$adminPassword;Pooling=false;Timeout=30;Command Timeout=120"
        $runtime = "Host=127.0.0.1;Port=$Port;Database=carv;Username=authority_runtime;Password=$runtimePassword;Timeout=30;Command Timeout=120"
        $env:ConnectionStrings__AuthorityDbMigration = $admin
        & dotnet (Join-Path $legacy[$short] 'AuthorizationAuthority.Api.dll') --migrate | Select-Object -Last 1 | Out-Host
        Remove-Item Env:ConnectionStrings__AuthorityDbMigration
        docker exec $name psql -U postgres -d carv -qAt -c 'SELECT version()' | Set-Content -Encoding ascii (Join-Path $runEvidence 'postgres-version.txt')
        docker image inspect postgres:18.0 --format '{{.Id}}' | Set-Content -Encoding ascii (Join-Path $runEvidence 'postgres-image.txt')
        $env:CARV_NEWBIN = Join-Path $new 'AuthorizationAuthority.Api.dll'
        $env:CARV_ADMIN = $admin; $env:CARV_RUNTIME = $runtime; $env:CARV_SQL = (Join-Path $WorkDir 'sql'); $env:CARV_EVIDENCE = $runEvidence
        if ($kind -eq 'A') {
            $env:CARV_LEGACY_LABEL = "legacy Authority Release build $short (legacy-$short-sha256.txt)"
            & (Join-Path $harnessA[$short] 'CarvHarness.exe') *> (Join-Path $runEvidence 'console.txt')
        }
        else {
            $env:CARV_AGENT = Join-Path $agents[$short] 'LegacyAgent.exe'
            $env:CARV_LEGACY = "legacy Authority Release build $short (legacy-$short-sha256.txt), driven by the legacy agent"
            $exe = if ($kind -eq 'F') { Join-Path $harnessF 'CarvHarnessF.exe' } else { Join-Path $harnessB 'CarvHarnessB.exe' }
            & $exe *> (Join-Path $runEvidence 'console.txt')
        }

        $code = $LASTEXITCODE
    }
    finally {
        docker rm -f $name 2>$null | Out-Null
        Remove-Item Env:CARV_NEWBIN, Env:CARV_ADMIN, Env:CARV_RUNTIME, Env:CARV_SQL, Env:CARV_EVIDENCE, Env:CARV_LEGACY_LABEL, Env:CARV_AGENT, Env:CARV_LEGACY -ErrorAction SilentlyContinue
    }

    $report = Join-Path $runEvidence 'carv-evidence.json'
    $checks = if (Test-Path $report) { Get-Content $report -Raw | ConvertFrom-Json } else { $null }
    [pscustomobject]@{
        Run = "harness $kind / legacy $short"; ExitCode = $code
        Checks = if ($checks) { $checks.checksTotal } else { 0 }; Failed = if ($checks) { $checks.checksFailed } else { -1 }
        ContainerRemoved = [string]::IsNullOrEmpty((docker ps -a --filter "name=$name" --format '{{.Names}}'))
    }
}

$results = foreach ($short in $legacy.Keys | Sort-Object) { Invoke-GateRun 'A' $short; Invoke-GateRun 'B' $short; Invoke-GateRun 'F' $short }
$results | Format-Table -AutoSize | Out-String | Write-Output
$results | ConvertTo-Json | Set-Content -Encoding ascii (Join-Path $Evidence 'summary.json')
if ($results | Where-Object { $_.ExitCode -ne 0 -or $_.Failed -ne 0 -or -not $_.ContainerRemoved }) {
    Write-Output 'E3-M2b-1 CARV PostgreSQL gate: FAILED'
    exit 1
}

Write-Output 'E3-M2b-1 CARV PostgreSQL gate: all runs passed'
exit 0
